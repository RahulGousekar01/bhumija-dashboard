import type { Officer } from "../../types/governance";
import { formatDate, formatDateTime } from "../dates";

/*
 * Official report builder (PDF via jsPDF + autotable, Excel via SheetJS),
 * the same libraries and versions the main portal already ships.
 *
 * Every report carries: DMG letterhead, a reference number, the data-as-of
 * date and batch, who generated it and when, the filters applied, page
 * numbers and a "computer-generated" footer.
 */

export interface ReportMeta {
  title: string;
  /** Short template code used in the reference number, e.g. "MIS". */
  code: string;
  asOfDate: string;
  batchId: string;
  provisional: boolean;
  filters: string[];
  officer: Officer;
}

export type ReportSection =
  | { heading: string; kind: "table"; columns: string[]; rows: (string | number)[][]; note?: string; numeric?: number[] }
  | { heading: string; kind: "fields"; rows: [string, string][] };

let sequence = 0;

/** DMG/BHU/<code>/<YYYYMMDD>/<seq>: the department's reference format (proposed). */
export const referenceNo = (code: string, asOfDate: string) =>
  `DMG/BHU/${code}/${asOfDate.replace(/-/g, "")}/${String(++sequence).padStart(4, "0")}`;

/** Built-in PDF fonts are WinAnsi-only: swap glyphs they cannot draw. */
const pdfText = (value: string | number): string =>
  String(value)
    .replace(/₹\s?/g, "Rs. ")
    .replace(/Δ/g, "Var. ")
    .replace(/≈/g, "~")
    .replace(/→/g, "->")
    .replace(/≥/g, ">=")
    .replace(/[^\x20-\x7E -ÿ–—‘’“”•…›]/g, "");

const fileStamp = (asOfDate: string) => asOfDate.replace(/-/g, "");

const metaRows = (meta: ReportMeta, reference: string, generatedAt: string): [string, string][] => [
  ["Reference no.", reference],
  ["Data as of", `${formatDate(meta.asOfDate)}, 23:59 IST (T-1 consolidated)`],
  ["Batch", `${meta.batchId}${meta.provisional ? " (some sources provisional)" : ""}`],
  ["Generated by", `${meta.officer.name}, ${meta.officer.designation}, ${meta.officer.office}`],
  ["Generated at", formatDateTime(generatedAt)],
  ["Filters applied", meta.filters.length ? meta.filters.join("; ") : "None (all jurisdictions)"],
];

let logoCache: Promise<string | null> | null = null;

/** The DMG emblem from public/img, as a data URL (null if unavailable). */
function loadLogo(): Promise<string | null> {
  logoCache ??= fetch(`${process.env.PUBLIC_URL ?? ""}/img/dmg-logo.png`)
    .then((response) => (response.ok ? response.blob() : null))
    .then(
      (blob) =>
        blob &&
        new Promise<string>((resolve, reject) => {
          const reader = new FileReader();
          reader.onload = () => resolve(String(reader.result));
          reader.onerror = reject;
          reader.readAsDataURL(blob);
        })
    )
    .catch(() => null);
  return logoCache;
}

const BRAND: [number, number, number] = [201, 58, 67]; // #C93A43
const ACCENT: [number, number, number] = [255, 107, 114]; // #FF6B72
const TEXT: [number, number, number] = [28, 33, 40];
const MUTED: [number, number, number] = [82, 91, 103];

export async function downloadPdf(meta: ReportMeta, sections: ReportSection[]): Promise<string> {
  const [{ jsPDF }, { default: autoTable }, logo] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
    loadLogo(),
  ]);

  const reference = referenceNo(meta.code, meta.asOfDate);
  const generatedAt = new Date().toISOString();
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;

  /* Letterhead */
  if (logo) doc.addImage(logo, "PNG", margin, 26, 44, 44);
  doc.setTextColor(...TEXT);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text("GOVERNMENT OF GOA", pageWidth / 2, 36, { align: "center" });
  doc.setFontSize(15);
  doc.text("Directorate of Mines & Geology", pageWidth / 2, 54, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...MUTED);
  doc.text("Bhumija Mining Management Portal", pageWidth / 2, 68, { align: "center" });
  doc.setDrawColor(...ACCENT);
  doc.setLineWidth(2);
  doc.line(margin, 80, pageWidth - margin, 80);

  doc.setTextColor(...BRAND);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text(pdfText(meta.title), margin, 102);

  autoTable(doc, {
    startY: 110,
    margin: { left: margin, right: margin },
    theme: "plain",
    styles: { fontSize: 8.5, cellPadding: 2.5, textColor: TEXT },
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 110, textColor: MUTED } },
    body: metaRows(meta, reference, generatedAt).map(([label, value]) => [label, pdfText(value)]),
  });

  /* Sections */
  for (const section of sections) {
    const lastY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 120;
    let y = lastY + 22;
    if (y > pageHeight - 90) {
      doc.addPage();
      y = 50;
    }
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10.5);
    doc.setTextColor(...TEXT);
    doc.text(pdfText(section.heading), margin, y);

    if (section.kind === "fields") {
      autoTable(doc, {
        startY: y + 6,
        margin: { left: margin, right: margin, bottom: 50 },
        theme: "grid",
        styles: { fontSize: 8.5, cellPadding: 4, lineColor: [226, 229, 233], textColor: TEXT },
        columnStyles: { 0: { fontStyle: "bold", cellWidth: 150, fillColor: [250, 251, 252] } },
        body: section.rows.map(([label, value]) => [pdfText(label), pdfText(value)]),
      });
    } else {
      const numeric = new Set(section.numeric ?? []);
      autoTable(doc, {
        startY: y + 6,
        margin: { left: margin, right: margin, bottom: 50 },
        theme: "striped",
        headStyles: { fillColor: BRAND, textColor: 255, fontSize: 8, fontStyle: "bold" },
        styles: { fontSize: 8, cellPadding: 3.5, textColor: TEXT, overflow: "linebreak" },
        alternateRowStyles: { fillColor: [250, 251, 252] },
        columnStyles: Object.fromEntries([...numeric].map((index) => [index, { halign: "right" }])),
        head: [section.columns.map(pdfText)],
        body: section.rows.length
          ? section.rows.map((row) => row.map(pdfText))
          : [[{ content: "No records", colSpan: section.columns.length, styles: { halign: "center", textColor: MUTED } }]],
      });
      if (section.note) {
        const noteY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 12;
        doc.setFont("helvetica", "italic");
        doc.setFontSize(7.5);
        doc.setTextColor(...MUTED);
        doc.text(pdfText(section.note), margin, noteY, { maxWidth: pageWidth - margin * 2 });
      }
    }
  }

  /* Footer on every page */
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.setDrawColor(226, 229, 233);
    doc.setLineWidth(0.5);
    doc.line(margin, pageHeight - 34, pageWidth - margin, pageHeight - 34);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text(
      pdfText(
        `Computer-generated report from Bhumija · ${reference} · T-1 consolidated data as of ${formatDate(meta.asOfDate)} 23:59 IST. Figures marked provisional are subject to reconciliation. No signature required.`
      ),
      margin,
      pageHeight - 22,
      { maxWidth: pageWidth - margin * 2 - 70 }
    );
    doc.text(`Page ${page} of ${pages}`, pageWidth - margin, pageHeight - 22, { align: "right" });
  }

  doc.save(`${meta.code}_${fileStamp(meta.asOfDate)}.pdf`);
  return reference;
}

export async function downloadExcel(meta: ReportMeta, sections: ReportSection[]): Promise<string> {
  const XLSX = await import("xlsx");
  const reference = referenceNo(meta.code, meta.asOfDate);
  const generatedAt = new Date().toISOString();
  const book = XLSX.utils.book_new();

  const cover = XLSX.utils.aoa_to_sheet([
    ["Government of Goa · Directorate of Mines & Geology"],
    ["Bhumija Mining Management Portal"],
    [],
    [meta.title],
    [],
    ...metaRows(meta, reference, generatedAt),
    [],
    ["Note", "Computer-generated report. T-1 consolidated data; figures marked provisional are subject to reconciliation."],
  ]);
  cover["!cols"] = [{ wch: 20 }, { wch: 90 }];
  XLSX.utils.book_append_sheet(book, cover, "Cover");

  const used = new Set<string>(["Cover"]);
  sections.forEach((section, index) => {
    const rows =
      section.kind === "fields"
        ? [["Field", "Value"], ...section.rows]
        : [section.columns, ...section.rows, ...(section.note ? [[], [section.note]] : [])];
    const sheet = XLSX.utils.aoa_to_sheet(rows);
    const widths = (rows[0] ?? []).map((_, column) =>
      Math.min(48, Math.max(10, ...rows.map((row) => String(row[column] ?? "").length + 2)))
    );
    sheet["!cols"] = widths.map((wch) => ({ wch }));

    // Sheet names: max 31 chars, no []:*?/\ and unique.
    let name = section.heading.replace(/[[\]:*?/\\]/g, " ").slice(0, 28).trim() || `Sheet ${index + 1}`;
    while (used.has(name)) name = `${name.slice(0, 26)} ${index + 1}`;
    used.add(name);
    XLSX.utils.book_append_sheet(book, sheet, name);
  });

  XLSX.writeFile(book, `${meta.code}_${fileStamp(meta.asOfDate)}.xlsx`);
  return reference;
}
