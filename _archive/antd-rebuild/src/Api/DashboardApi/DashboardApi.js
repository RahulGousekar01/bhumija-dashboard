/*
 * Dashboard API (prototype).
 *
 * Each function returns the same envelope as the portal's gateway calls:
 *   { ErrorYn: "N" | "Y", ErrMsg, Data }   where Data = JSON string of { Table: [...] }
 * so the views read results exactly as other portal screens do:
 *   JSON.parse(response.Data).Table
 *
 * To connect the real backend, replace the body of each function with the
 * usual axios.post(BASE_URL, encodeAndEncryptObjectValues(body), …) call.
 * Filters arrive as { financialYear, district, taluka, organisation, role }.
 */
import { jsPDF } from "jspdf";
import { ALL, CURRENT_PARTY, DISTRICTS, ROLES } from "constants/DashboardConstant";
import {
  DISTRICT_SHARE,
  ORGANISATION_SHARE,
  TALUKA_SHARE,
  permits,
  stockStatewide,
  tripSheetsStatewide,
} from "data/sampleData";
import { financialYearRange, formatDate, formatNumber, getAsOnDate } from "utils/dateUtils";

const DELAY_MS = 300;

const respond = (table) =>
  new Promise((resolve) =>
    setTimeout(() => resolve({ ErrorYn: "N", ErrMsg: "", Data: JSON.stringify({ Table: table }) }), DELAY_MS)
  );

const fail = (message) => Promise.resolve({ ErrorYn: "Y", ErrMsg: message, Data: null });

/** Reads the Table from a gateway response; throws on ErrorYn = "Y". */
export const readTable = (response) => {
  if (!response || response.ErrorYn !== "N") throw new Error(response?.ErrMsg || "No Data Found");
  return JSON.parse(response.Data).Table;
};

/* ---------- Scoping (done by the server in the portal) ---------- */

const organisationFor = (filters) => (filters.role === ROLES.PARTY ? CURRENT_PARTY : filters.organisation);

const matchesScope = (permit, filters) => {
  const [fyStart, fyEnd] = financialYearRange(filters.financialYear);
  const organisation = organisationFor(filters);
  const appl = new Date(permit.appldate);
  return (
    appl >= fyStart.toDate() &&
    appl <= fyEnd.toDate() &&
    (filters.district === ALL || permit.district === filters.district) &&
    (filters.taluka === ALL || permit.taluka === filters.taluka) &&
    (organisation === ALL || permit.party === organisation)
  );
};

const districtOf = (taluka) =>
  Object.keys(DISTRICTS).find((district) => DISTRICTS[district].includes(taluka));

/** Share of statewide activity covered by the filters (for trip sheet and stock totals). */
const scopeShare = (filters) => {
  const organisation = organisationFor(filters);
  let share = 1;
  if (filters.taluka !== ALL) share *= (DISTRICT_SHARE[districtOf(filters.taluka)] ?? 0) * (TALUKA_SHARE[filters.taluka] ?? 0);
  else if (filters.district !== ALL) share *= DISTRICT_SHARE[filters.district] ?? 0;
  if (organisation !== ALL) share *= ORGANISATION_SHARE[organisation] ?? 0;
  return share;
};


/* ---------- Endpoints ---------- */

/** Permit applications in scope, newest first. */
export const dashboardPermitList = async (filters) =>
  respond(permits.filter((permit) => matchesScope(permit, filters)));

/** Trip sheets generated on the T-1 day. */
export const dashboardTripSheetSummary = async (filters) => {
  const share = scopeShare(filters);
  const road = Math.round(tripSheetsStatewide.road * share);
  const barge = Math.round(tripSheetsStatewide.barge * share);
  const closed = Math.min(road + barge, Math.round(tripSheetsStatewide.closed * share));
  return respond([
    {
      generated: road + barge,
      road,
      barge,
      closed,
      intransit: road + barge - closed,
      quantity: Math.round(tripSheetsStatewide.quantity * share),
    },
  ]);
};

/** Stock position by source at the end of the T-1 day. */
export const dashboardStockSummary = async (filters) => {
  const share = scopeShare(filters);
  return respond(stockStatewide.map((row) => ({ source: row.source, quantity: Math.round((row.quantity * share) / 10) * 10 })));
};

/**
 * Permit certificate as base64 PDF, like the portal's downloadPermitCertificate.
 * The real certificate is generated by the server; this is a placeholder.
 */
export const downloadPermitCertificate = async (ackno) => {
  const permit = permits.find((item) => item.ackno === ackno);
  if (!permit || permit.status !== "Approved") return fail("Certificate is available only for approved permits.");

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const line = (label, value, y) => {
    doc.setFont("helvetica", "bold");
    doc.text(label, 60, y);
    doc.setFont("helvetica", "normal");
    doc.text(String(value), 220, y);
  };

  doc.setFontSize(11);
  doc.text("GOVERNMENT OF GOA", 297, 60, { align: "center" });
  doc.setFontSize(15);
  doc.text("Directorate of Mines & Geology", 297, 80, { align: "center" });
  doc.setFontSize(13);
  doc.text(`${permit.permittype} Permit`, 297, 110, { align: "center" });
  doc.setDrawColor(255, 107, 114);
  doc.line(60, 122, 535, 122);

  doc.setFontSize(10.5);
  const rows = [
    ["Permit No", permit.permitno],
    ["Ack No", permit.ackno],
    ["Party", permit.party],
    ["Location", `${permit.locname}, ${permit.taluka}, ${permit.district}`],
    ["Ore Source", permit.oresource],
    ["Purpose", permit.purpose],
    ["Mineral Details", `${permit.mineraldetail} (${permit.gradeslab})`],
    ["Approved Quantity", `${formatNumber(permit.approvedqty)} MT`],
    ["Application Date", formatDate(permit.appldate)],
    ["Valid Upto", formatDate(permit.validupto)],
  ];
  rows.forEach(([label, value], index) => line(label, value, 160 + index * 22));

  doc.setFontSize(8);
  doc.setTextColor(110);
  doc.text(
    `Prototype certificate generated from sample data on ${formatDate(getAsOnDate().add(1, "day"))}. The portal issues the official certificate.`,
    60,
    800
  );

  const base64 = doc.output("datauristring").split(",")[1];
  return respond([{ filename: `${permit.permitno.replace(/\//g, "-")}.pdf`, content: base64 }]);
};
